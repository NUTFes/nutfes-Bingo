#!/usr/bin/env node
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const selfHostDir = join(repoRoot, "supabase", "self-host");
const source = join(selfHostDir, "upstream", ".env.example");
const target = process.env.SUPABASE_SELFHOST_ENV || join(selfHostDir, ".env.local");
const force = process.argv.includes("--force");

if (!existsSync(source)) {
  console.error(
    "Missing supabase/self-host/upstream/.env.example. Run `mise run supabase:selfhost:sync` first.",
  );
  process.exit(1);
}

if (existsSync(target) && !force) {
  console.log(`${target} already exists; use --force to regenerate.`);
  process.exit(0);
}

function randomUrlSafe(bytes = 32) {
  return randomBytes(bytes).toString("base64url");
}

function randomHex(bytes = 16) {
  return randomBytes(bytes).toString("hex");
}

function jwt(role, secret) {
  const now = Math.floor(Date.now() / 1000);
  const header = { alg: "HS256", typ: "JWT" };
  const payload = {
    role,
    iss: "supabase-demo",
    iat: now,
    exp: now + 60 * 60 * 24 * 365 * 10,
  };
  const encode = (value) => Buffer.from(JSON.stringify(value)).toString("base64url");
  const unsigned = `${encode(header)}.${encode(payload)}`;
  const signature = createHmac("sha256", secret).update(unsigned).digest("base64url");
  return `${unsigned}.${signature}`;
}

const jwtSecret = randomUrlSafe(48);
const generated = {
  POSTGRES_PASSWORD: randomUrlSafe(36),
  JWT_SECRET: jwtSecret,
  ANON_KEY: jwt("anon", jwtSecret),
  SERVICE_ROLE_KEY: jwt("service_role", jwtSecret),
  ANON_KEY_ASYMMETRIC: jwt("anon", jwtSecret),
  SERVICE_ROLE_KEY_ASYMMETRIC: jwt("service_role", jwtSecret),
  SUPABASE_PUBLISHABLE_KEY: `sb_publishable_${randomUrlSafe(32)}`,
  SUPABASE_SECRET_KEY: `sb_secret_${randomUrlSafe(48)}`,
  JWT_KEYS: "",
  JWT_JWKS: "",
  DASHBOARD_USERNAME: "nutfes",
  DASHBOARD_PASSWORD: randomUrlSafe(24),
  SECRET_KEY_BASE: randomUrlSafe(64),
  VAULT_ENC_KEY: randomHex(16),
  PG_META_CRYPTO_KEY: randomUrlSafe(32),
  LOGFLARE_PUBLIC_ACCESS_TOKEN: randomUrlSafe(32),
  LOGFLARE_PRIVATE_ACCESS_TOKEN: randomUrlSafe(48),
  S3_PROTOCOL_ACCESS_KEY_ID: randomHex(16),
  S3_PROTOCOL_ACCESS_KEY_SECRET: randomHex(32),
  SUPABASE_PUBLIC_URL: "https://bingo-stg.nutfes.net/supabase",
  API_EXTERNAL_URL: "https://bingo-stg.nutfes.net/supabase",
  SITE_URL: "https://bingo-stg.nutfes.net",
  ADDITIONAL_REDIRECT_URLS:
    "https://bingo-stg.nutfes.net/**,https://bingo-stg.nutfes.net/auth/confirm",
  DISABLE_SIGNUP: "true",
  ENABLE_EMAIL_SIGNUP: "false",
  ENABLE_PHONE_SIGNUP: "false",
  KONG_HTTP_PORT: "127.0.0.1:8000",
  KONG_HTTPS_PORT: "127.0.0.1:8443",
  POOLER_TENANT_ID: `nutfes-${randomHex(8)}`,
  OPENAI_API_KEY: "",
};

const seen = new Set();
const body = readFileSync(source, "utf8")
  .split("\n")
  .map((line) => {
    const match = line.match(/^([A-Z0-9_]+)=/);
    if (!match) return line;
    const key = match[1];
    if (!Object.prototype.hasOwnProperty.call(generated, key)) return line;
    seen.add(key);
    return `${key}=${generated[key]}`;
  })
  .join("\n");

const missing = Object.keys(generated).filter((key) => !seen.has(key));
const suffix =
  missing.length > 0 ? `\n${missing.map((key) => `${key}=${generated[key]}`).join("\n")}\n` : "";

writeFileSync(
  target,
  `${body}${suffix}\n# Generated by scripts/supabase-selfhost-init-env.mjs. Do not commit this file.\n`,
);

console.log(`Generated ${target}`);
console.log("Copy these variable names, not values, into .env.production.local as needed:");
console.log("  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY <- SUPABASE_PUBLISHABLE_KEY");
console.log("  SUPABASE_SECRET_KEY <- SUPABASE_SECRET_KEY");
