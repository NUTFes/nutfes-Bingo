#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const selfHostEnvPath =
  process.env.SUPABASE_SELFHOST_ENV || join(repoRoot, "supabase", "self-host", ".env.local");
const examplePath = join(repoRoot, ".env.production.example");
const targetPath = process.env.PROD_ENV || join(repoRoot, ".env.production.local");
const force = process.argv.includes("--force");

function parseEnv(path) {
  const env = new Map();
  for (const rawLine of readFileSync(path, "utf8").split("\n")) {
    const line = rawLine.trimEnd();
    if (line === "" || line.trimStart().startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator === -1) continue;
    const key = line.slice(0, separator);
    let value = line.slice(separator + 1);
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env.set(key, value);
  }
  return env;
}

if (!existsSync(selfHostEnvPath)) {
  console.error(`Missing ${selfHostEnvPath}. Run \`mise run supabase:selfhost:init-env\` first.`);
  process.exit(1);
}

if (!existsSync(examplePath)) {
  console.error(`Missing ${examplePath}.`);
  process.exit(1);
}

if (existsSync(targetPath) && !force) {
  console.log(`${targetPath} already exists; use --force to regenerate.`);
  process.exit(0);
}

const selfHostEnv = parseEnv(selfHostEnvPath);
const replacements = new Map([
  ["NEXT_PUBLIC_SUPABASE_URL", "https://bingo-stg.nutfes.net/supabase"],
  ["NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY", selfHostEnv.get("SUPABASE_PUBLISHABLE_KEY")],
  ["SUPABASE_SECRET_KEY", selfHostEnv.get("SUPABASE_SECRET_KEY")],
  ["SUPABASE_SERVER_URL", "http://supabase_kong_nutfes-Bingo:8000"],
  ["SUPABASE_UPSTREAM", "supabase_kong_nutfes-Bingo:8000"],
  ["SUPABASE_DOCKER_NETWORK", "supabase_network_nutfes-Bingo"],
]);

const missing = [...replacements].filter(([, value]) => !value).map(([key]) => key);
if (missing.length > 0) {
  console.error(`Missing required generated values: ${missing.join(", ")}`);
  process.exit(1);
}

const next = readFileSync(examplePath, "utf8")
  .split("\n")
  .map((line) => {
    const match = line.match(/^([A-Z0-9_]+)=/);
    if (!match || !replacements.has(match[1])) return line;
    return `${match[1]}=${replacements.get(match[1])}`;
  })
  .join("\n");

writeFileSync(
  targetPath,
  `${next}\n# Generated by scripts/prod-init-env-from-selfhost.mjs. Do not commit this file.\n`,
);
console.log(`Generated ${targetPath}`);
console.log(
  "Cloudflared tunnel token was not written; export CLOUDFLARED_TUNNEL_TOKEN at deploy time.",
);
